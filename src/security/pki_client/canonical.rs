//! Canonical key pair of an ITS-S (ETSI TS 102 941 V2.2.1 clause 6.1.2).
//!
//! The ITS-S signs its initial enrolment request with the canonical private key
//! (signer `self`, clause 6.2.3.2.1); the EA verifies it with the canonical
//! public key registered for the canonical identifier (`itsId`) before the first
//! request. An unregistered identifier is refused with `unknownits`, a request
//! signed with another key with `invalidsignature`.
//!
//! [`load_or_create_canonical_key`] keeps the key pair in two files:
//! - `<path>`: the private key, PKCS#8 PEM, mode 0600, created once (never
//!   overwritten);
//! - `<path minus .pem>.pub.pem`: the public key, SubjectPublicKeyInfo PEM, to be
//!   registered with the EA (pythonpki: `ea-tool register --its-id ...
//!   --public-key ...`).
//!
//! The canonical identifier may be assigned (manufacturer) or generated by the
//! ITS-S (clause 6.1.3); [`canonical_id`] generates a stable one from the public
//! key: the last 8 octets of SHA-256 over the DER SubjectPublicKeyInfo.
//!
//! The formats and the identifier are the same in FlexStack
//! (`flexstack.security.pki_client.canonical`).

use std::path::{Path, PathBuf};

use p256::pkcs8::{DecodePrivateKey, DecodePublicKey, EncodePrivateKey, EncodePublicKey, LineEnding};
use sha2::{Digest, Sha256};

use super::client::PkiError;

/// The canonical key pair kept on disk.
#[derive(Debug, Clone)]
pub struct CanonicalKey {
    /// Private scalar (32 octets), as [`super::PkiClient::new`] takes it.
    pub scalar: Vec<u8>,
    /// Public key, SubjectPublicKeyInfo PEM.
    pub public_pem: String,
    pub private_path: PathBuf,
    pub public_path: PathBuf,
    /// The private key file was created by this call.
    pub created: bool,
}

impl CanonicalKey {
    /// The canonical identifier generated from the public key ([`canonical_id`]).
    pub fn its_id(&self) -> [u8; 8] {
        canonical_id(&self.public_pem).expect("public key PEM written by this module")
    }

    /// The pythonpki command that registers this ITS-S with the EA (`its_id`
    /// defaults to [`CanonicalKey::its_id`]).
    pub fn registration_command(&self, its_id: Option<&[u8]>) -> String {
        let id = its_id.map(<[u8]>::to_vec).unwrap_or_else(|| self.its_id().to_vec());
        format!(
            "ea-tool register --its-id {} --public-key {}",
            hex(&id),
            self.public_path.display()
        )
    }
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn invalid(message: impl Into<String>) -> PkiError {
    PkiError::Io(std::io::Error::new(
        std::io::ErrorKind::InvalidData,
        message.into(),
    ))
}

/// `canonical_key.pem` -> `canonical_key.pub.pem`.
pub fn public_key_path(private_path: &Path) -> PathBuf {
    let name = private_path
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_default();
    let stem = name.strip_suffix(".pem").unwrap_or(&name);
    private_path.with_file_name(format!("{stem}.pub.pem"))
}

/// Canonical identifier generated from a public key PEM: the last 8 octets of
/// SHA-256 over its DER SubjectPublicKeyInfo.
pub fn canonical_id(public_pem: &str) -> Result<[u8; 8], PkiError> {
    let key = p256::PublicKey::from_public_key_pem(public_pem)
        .map_err(|e| invalid(format!("canonical public key: {e}")))?;
    let der = key
        .to_public_key_der()
        .map_err(|e| invalid(format!("canonical public key: {e}")))?;
    let digest = Sha256::digest(der.as_bytes());
    let mut id = [0u8; 8];
    id.copy_from_slice(&digest[24..]);
    Ok(id)
}

/// The NIST P-256 private key of a PEM: PKCS#8 (`PRIVATE KEY`) or SEC1 (`EC PRIVATE KEY`).
fn secret_key(private_pem: &str) -> Result<p256::SecretKey, PkiError> {
    p256::SecretKey::from_pkcs8_pem(private_pem)
        .or_else(|_| p256::SecretKey::from_sec1_pem(private_pem))
        .map_err(|_| invalid("the canonical key must be a NIST P-256 private key (PEM)"))
}

/// SubjectPublicKeyInfo PEM of a canonical private key PEM (P-256).
pub fn public_pem(private_pem: &str) -> Result<String, PkiError> {
    secret_key(private_pem)?
        .public_key()
        .to_public_key_pem(LineEnding::LF)
        .map_err(|e| invalid(format!("canonical public key: {e}")))
}

fn create_private(path: &Path) -> Result<(), PkiError> {
    use std::io::Write;
    let key = p256::SecretKey::random(&mut rand::thread_rng());
    let pem = key
        .to_pkcs8_pem(LineEnding::LF)
        .map_err(|e| invalid(format!("canonical private key: {e}")))?;
    let mut options = std::fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::OpenOptionsExt;
        options.mode(0o600);
    }
    options.open(path)?.write_all(pem.as_bytes())?;
    Ok(())
}

/// The canonical key pair kept at `path`, created (NIST P-256) when absent.
pub fn load_or_create_canonical_key(path: &Path) -> Result<CanonicalKey, PkiError> {
    let public_path = public_key_path(path);
    let mut created = false;
    if !path.exists() {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        create_private(path)?;
        created = true;
    }
    let private_pem = std::fs::read_to_string(path)?;
    let secret = secret_key(&private_pem)?;
    let public = public_pem(&private_pem)?;
    if std::fs::read_to_string(&public_path).ok().as_deref() != Some(public.as_str()) {
        std::fs::write(&public_path, &public)?;
    }
    Ok(CanonicalKey {
        scalar: secret.to_bytes().to_vec(),
        public_pem: public,
        private_path: path.to_path_buf(),
        public_path,
        created,
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::security::pki_client::client::PkiClient;
    use crate::security::pki_client::ts_pki::{signed_data, Transport, TsPki};
    use crate::security::security_asn::ieee1609_dot2::SignerIdentifier;
    use crate::security::security_asn::ieee1609_dot2_base_types::{
        EccP256CurvePoint, PublicVerificationKey,
    };
    use std::sync::atomic::{AtomicU64, Ordering};
    use std::sync::{Arc, Mutex};

    /// Frozen vector, also in FlexStack (test_canonical.py): the NIST P-256
    /// private key of RFC 6979 A.2.5 as PKCS#8 PEM, its SubjectPublicKeyInfo PEM
    /// and the generated canonical identifier.
    const VECTOR_PRIVATE: &str = "-----BEGIN PRIVATE KEY-----\n\
MIGHAgEAMBMGByqGSM49AgEGCCqGSM49AwEHBG0wawIBAQQgya+p2EW6dRZrXCFX\n\
Z7HWk05Qw9s26JsSe4piKxIPZyGhRANCAARg/tS6JVqdMclh63TGNW1owEm4kjth\n\
+mzmaWIuYPKftnkD/hAIuLyZpBrp6VYovGTy8bIMLX6fUXejwpTURiKZ\n\
-----END PRIVATE KEY-----\n";
    const VECTOR_PUBLIC: &str = "-----BEGIN PUBLIC KEY-----\n\
MFkwEwYHKoZIzj0CAQYIKoZIzj0DAQcDQgAEYP7UuiVanTHJYet0xjVtaMBJuJI7\n\
Yfps5mliLmDyn7Z5A/4QCLi8maQa6elWKLxk8vGyDC1+n1F3o8KU1EYimQ==\n\
-----END PUBLIC KEY-----\n";
    const VECTOR_ITS_ID: [u8; 8] = [0xcb, 0xe0, 0xf0, 0x81, 0x5a, 0x07, 0xec, 0xd4];

    fn temp_dir() -> PathBuf {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        std::env::temp_dir().join(format!(
            "rustflexstack-canonical-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::SeqCst)
        ))
    }

    /// PublicVerificationKey of a SubjectPublicKeyInfo PEM (as an EA registers it).
    fn registered(public: &str) -> PublicVerificationKey {
        use p256::elliptic_curve::sec1::ToEncodedPoint;
        let point = p256::PublicKey::from_public_key_pem(public)
            .unwrap()
            .to_encoded_point(true);
        let x = point.x().unwrap().to_vec().into();
        PublicVerificationKey::ecdsaNistP256(if point.as_bytes()[0] == 2 {
            EccP256CurvePoint::compressed_y_0(x)
        } else {
            EccP256CurvePoint::compressed_y_1(x)
        })
    }

    #[test]
    fn created_once_and_private() {
        let path = temp_dir().join("pki").join("canonical_key.pem");
        let first = load_or_create_canonical_key(&path).unwrap();
        assert!(first.created);
        assert_eq!(first.scalar.len(), 32);
        assert_eq!(first.public_path, path.with_file_name("canonical_key.pub.pem"));
        assert_eq!(std::fs::read_to_string(&first.public_path).unwrap(), first.public_pem);
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&path).unwrap().permissions().mode();
            assert_eq!(mode & 0o077, 0);
        }
        let second = load_or_create_canonical_key(&path).unwrap();
        assert!(!second.created);
        assert_eq!(
            (second.scalar, second.public_pem),
            (first.scalar, first.public_pem)
        );
    }

    #[test]
    fn public_file_is_rewritten_from_the_private_key() {
        let path = temp_dir().join("canonical_key.pem");
        let key = load_or_create_canonical_key(&path).unwrap();
        std::fs::write(&key.public_path, "stale").unwrap();
        load_or_create_canonical_key(&path).unwrap();
        assert_eq!(std::fs::read_to_string(&key.public_path).unwrap(), key.public_pem);
        std::fs::remove_file(&key.public_path).unwrap();
        load_or_create_canonical_key(&path).unwrap();
        assert_eq!(std::fs::read_to_string(&key.public_path).unwrap(), key.public_pem);
    }

    #[test]
    fn frozen_vector() {
        let path = temp_dir().join("canonical_key.pem");
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, VECTOR_PRIVATE).unwrap();
        let key = load_or_create_canonical_key(&path).unwrap();
        assert!(!key.created);
        assert_eq!(key.public_pem, VECTOR_PUBLIC);
        assert_eq!(public_pem(VECTOR_PRIVATE).unwrap(), VECTOR_PUBLIC);
        assert_eq!(key.its_id(), VECTOR_ITS_ID);
        assert_eq!(canonical_id(VECTOR_PUBLIC).unwrap(), VECTOR_ITS_ID);
        assert_eq!(
            hex(&key.scalar),
            "c9afa9d845ba75166b5c215767b1d6934e50c3db36e89b127b8a622b120f6721"
        );
    }

    #[test]
    fn sec1_pem_is_read_and_other_keys_refused() {
        let sec1 = p256::SecretKey::random(&mut rand::thread_rng())
            .to_sec1_pem(LineEnding::LF)
            .unwrap();
        assert!(public_pem(&sec1).unwrap().contains("BEGIN PUBLIC KEY"));
        let p384 = p384::SecretKey::random(&mut rand::thread_rng())
            .to_pkcs8_pem(LineEnding::LF)
            .unwrap();
        assert!(public_pem(&p384).is_err());
        assert!(public_pem("junk").is_err());
        assert!(canonical_id("junk").is_err());
        let path = temp_dir().join("canonical_key.pem");
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, p384.as_bytes()).unwrap();
        assert!(load_or_create_canonical_key(&path).is_err());
    }

    #[test]
    fn public_key_path_and_registration_command() {
        assert_eq!(
            public_key_path(Path::new("/x/key.pem")),
            PathBuf::from("/x/key.pub.pem")
        );
        assert_eq!(
            public_key_path(Path::new("/x/key")),
            PathBuf::from("/x/key.pub.pem")
        );
        let dir = temp_dir();
        let key = load_or_create_canonical_key(&dir.join("a.pem")).unwrap();
        assert_eq!(
            key.registration_command(Some(&[1, 2])),
            format!("ea-tool register --its-id 0102 --public-key {}", key.public_path.display())
        );
        assert_eq!(
            key.registration_command(None),
            format!(
                "ea-tool register --its-id {} --public-key {}",
                hex(&key.its_id()),
                key.public_path.display()
            )
        );
        let other = load_or_create_canonical_key(&dir.join("b.pem")).unwrap();
        assert_ne!(key.its_id(), other.its_id());
    }

    struct Flow {
        pki: Arc<Mutex<TsPki>>,
        transport: Transport,
        dir: PathBuf,
        key: CanonicalKey,
    }

    impl Flow {
        fn new() -> Flow {
            let pki = Arc::new(Mutex::new(TsPki::new()));
            let transport = Transport::new(Arc::clone(&pki));
            let dir = temp_dir();
            let key = load_or_create_canonical_key(&dir.join("canonical_key.pem")).unwrap();
            Flow {
                pki,
                transport,
                dir,
                key,
            }
        }

        fn client(&self) -> PkiClient {
            let p = self.pki.lock().unwrap();
            PkiClient::new(
                self.transport.ea_url.clone(),
                self.transport.aa_url.clone(),
                p.ea.own.cert.clone(),
                p.aa.own.cert.clone(),
                p.root.cert.clone(),
                Some(self.key.scalar.clone()),
                self.dir.clone(),
                Some(self.key.its_id()),
                None,
            )
            .with_transport(Box::new(self.transport.clone()))
        }

        fn last_signer(&self) -> SignerIdentifier {
            let p = self.pki.lock().unwrap();
            signed_data(&p.enrolments.last().unwrap().outer).signer.clone()
        }
    }

    /// Generate (ITS-S) → register the public key (EA) → enrol and get an AT.
    #[test]
    fn registered_key_enrols() {
        let flow = Flow::new();
        let mut client = flow.client();
        assert_eq!(client.canonical_public_key(), registered(&flow.key.public_pem));
        flow.pki
            .lock()
            .unwrap()
            .register(&flow.key.its_id(), registered(&flow.key.public_pem));
        client.provision(None, None, None).unwrap();
        assert!(matches!(flow.last_signer(), SignerIdentifier::R_self(_)));
        assert_eq!(
            flow.pki.lock().unwrap().enrolments[0].ec().its_id.to_vec(),
            flow.key.its_id().to_vec()
        );
    }

    #[test]
    fn unregistered_or_other_key_is_refused() {
        let flow = Flow::new();
        assert!(flow.client().enroll(None, None).is_err());
        let other = load_or_create_canonical_key(&flow.dir.join("other.pem")).unwrap();
        flow.pki
            .lock()
            .unwrap()
            .register(&flow.key.its_id(), registered(&other.public_pem));
        assert!(flow.client().enroll(None, None).is_err());
        let p = flow.pki.lock().unwrap();
        assert_eq!(p.enrolments.len(), 2);
        assert!(p.enrolments.iter().all(|r| !r.checks["outer"]));
    }

    #[test]
    fn later_runs_rekey_with_the_saved_ec() {
        let flow = Flow::new();
        flow.pki
            .lock()
            .unwrap()
            .register(&flow.key.its_id(), registered(&flow.key.public_pem));
        flow.client().enroll(None, None).unwrap();
        let mut later = flow.client();
        assert!(later.load_ec_from_disk(None).is_some());
        later.enroll(None, None).unwrap();
        assert!(matches!(flow.last_signer(), SignerIdentifier::digest(_)));
    }
}
